function showNotification(message, type = 'success') {
    const notification = document.getElementById('notification');
    if (!notification) {
        console.log(`[Notification ${type}]:`, message);
        return;
    }
    const title = document.getElementById('notificationTitle');
    const msg = document.getElementById('notificationMessage');
    if (title) title.textContent = type === 'success' ? 'Successo' : type === 'error' ? 'Errore' : 'Avviso';
    if (msg) msg.textContent = message;
    notification.className = 'notification ' + type;
    notification.classList.add('show');
    setTimeout(() => {
        if (notification) notification.classList.remove('show');
    }, 3000);
}

function updateCloudStatus(status, message) {
    const statusEl = document.getElementById('cloudStatus');
    const textEl = document.getElementById('cloudStatusText');
    if (statusEl && textEl) {
        statusEl.className = 'sync-status ' + status;
        textEl.textContent = message || (status === 'online' ? 'Sincronizzato' : status === 'offline' ? 'Offline (Locale)' : 'In corso...');

        const icon = statusEl.querySelector('i');
        if (icon) {
            if (status === 'syncing') {
                icon.className = 'fas fa-sync-alt fa-spin';
            } else if (status === 'error') {
                icon.className = 'fas fa-exclamation-triangle';
            } else if (status === 'online') {
                icon.className = 'fas fa-satellite-dish';
            } else {
                icon.className = 'fas fa-cloud';
            }
        }
    }

    const settingsBadge = document.getElementById('cloudSyncBadgeSettings');
    if (settingsBadge) {
        settingsBadge.className = 'sync-status ' + status;
        const sSpan = settingsBadge.querySelector('span');
        if (sSpan) sSpan.textContent = message || (status === 'online' ? 'Multi-Dispositivo Attivo' : 'Offline (Locale)');
    }
}

const CloudSyncService = {
    channel: null,
    isSyncing: false,
    _pushTimeout: null,

    init() {
        if (typeof BroadcastChannel !== 'undefined') {
            try {
                this.channel = new BroadcastChannel('inventario_sync_channel');
                this.channel.onmessage = (event) => {
                    if (event.data && event.data.type === 'DATA_UPDATED') {
                        this.handleRemoteUpdate(event.data.payload);
                    }
                };
            } catch (e) {
                console.warn('BroadcastChannel non supportato:', e);
            }
        }

        window.addEventListener('storage', (e) => {
            if (e.key === 'inventario_pro_data' && e.newValue) {
                try {
                    const parsed = JSON.parse(e.newValue);
                    this.handleRemoteUpdate(parsed);
                } catch (err) { }
            }
        });

        updateCloudStatus('online', 'Multi-Dispositivo Attivo');
    },

    handleRemoteUpdate(remoteData) {
        if (!remoteData || !remoteData.lastModified) return;
        const localMod = appData.lastModified || 0;
        if (remoteData.lastModified > localMod) {
            appData = remoteData;
            updateAll();
            showNotification('Dati sincronizzati con un altro dispositivo', 'info');
        }
    },

    pushLocalChanges() {
        appData.lastModified = Date.now();
        localStorage.setItem('inventario_pro_data', JSON.stringify(appData));

        if (this.channel) {
            try {
                this.channel.postMessage({
                    type: 'DATA_UPDATED',
                    payload: appData
                });
            } catch (e) { }
        }

        updateCloudStatus('online', 'Sincronizzato');
    }
};

function saveToCloud() {
    CloudSyncService.pushLocalChanges();
}

function loadLocalData() {
    const saved = localStorage.getItem('inventario_pro_data');
    if (saved) {
        try {
            const parsed = JSON.parse(saved);
            if (parsed && Array.isArray(parsed.products) && parsed.products.length > 0) {
                // Sincronizza quantità/prezzi preservando la corretta classificazione dei reparti da catalogo
                const savedMap = new Map(parsed.products.map(p => [p.id, p]));
                appData.products.forEach(p => {
                    const existing = savedMap.get(p.id);
                    if (existing) {
                        p.quantity = existing.quantity !== undefined ? existing.quantity : p.quantity;
                        p.price = existing.price !== undefined ? existing.price : p.price;
                        p.status = existing.status || p.status;
                    }
                });
                // Includi eventuali prodotti personalizzati creati dall'utente
                parsed.products.forEach(p => {
                    if (!appData.products.some(orig => orig.id === p.id)) {
                        appData.products.push(p);
                    }
                });
                if (parsed.monthlySnapshots) appData.monthlySnapshots = parsed.monthlySnapshots;
                if (parsed.settings) appData.settings = parsed.settings;
                if (parsed.lastModified) appData.lastModified = parsed.lastModified;
            }
        } catch (e) {
            console.error('Errore parsing dati locali:', e);
        }
    }
}

