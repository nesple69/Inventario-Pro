function renderAllProductsTable() {
    updateProductDepartmentCounters();

    const tbody = document.getElementById('allProductsTableBody');
    if (!tbody) return;

    const searchInput = document.getElementById('productSearchInput');
    const searchTerm = searchInput ? searchInput.value.toLowerCase().trim() : '';

    const catSelect = document.getElementById('filterCategorySelect');
    const selectedCategory = catSelect ? catSelect.value : '';

    const supSelect = document.getElementById('filterSupplierSelect');
    const selectedSupplier = supSelect ? supSelect.value : '';

    let filtered = appData.products || [];

    // 1. Filtro Rapido per Reparto (Cucina / Bar / Bowling / Consumabili)
    if (currentProductDeptFilter && currentProductDeptFilter !== 'tutti') {
        filtered = filtered.filter(p => {
            const pDept = (p.department || '').toLowerCase();
            const pCat = (p.category || '').toLowerCase();
            if (currentProductDeptFilter === 'cucina') {
                return pDept === 'cucina' || pCat === 'cucina';
            }
            if (currentProductDeptFilter === 'bar') {
                return pDept === 'bar' || pCat === 'beverage';
            }
            if (currentProductDeptFilter === 'bowling') {
                return pDept === 'bowling' || pCat === 'bowling';
            }
            if (currentProductDeptFilter === 'consumabili') {
                return pCat === 'consumabili' || pDept === 'entrambi';
            }
            return true;
        });
    } else if (currentRole !== 'admin') {
        filtered = getProductsForRole(currentRole);
    }

    // 2. Filtro Categoria
    if (selectedCategory) {
        filtered = filtered.filter(p => (p.category || '') === selectedCategory);
    }

    // 3. Filtro Fornitore
    if (selectedSupplier) {
        filtered = filtered.filter(p => (p.supplier || '') === selectedSupplier);
    }

    // 4. Ricerca Testuale (Nome, Categoria, Sottocategoria, Fornitore)
    if (searchTerm) {
        filtered = filtered.filter(p =>
            (p.name && p.name.toLowerCase().includes(searchTerm)) ||
            (p.category && p.category.toLowerCase().includes(searchTerm)) ||
            (p.subcategory && p.subcategory.toLowerCase().includes(searchTerm)) ||
            (p.supplier && p.supplier.toLowerCase().includes(searchTerm))
        );
    }

    if (filtered.length === 0) {
        tbody.innerHTML = '<tr><td colspan="8" style="text-align: center; color: var(--gray); padding: 2rem;">Nessun prodotto trovato con i filtri selezionati</td></tr>';
        return;
    }

    tbody.innerHTML = filtered.map(p => createProductTableRow(p)).join('');
}

function addProductFromForm() {
    const name = document.getElementById('productName')?.value.trim();
    const category = document.getElementById('productCategory')?.value;
    const department = document.getElementById('productDepartment')?.value || 'entrambi';
    const subcategory = document.getElementById('productSubcategory')?.value;
    const quantity = parseFloat(document.getElementById('productQuantity')?.value) || 0;
    const unit = document.getElementById('productUnit')?.value || 'pezzi';
    const price = parseFloat(document.getElementById('productPrice')?.value) || 0;
    const supplier = document.getElementById('productSupplier')?.value || '';

    if (!name) {
        showNotification('Inserisci il nome del prodotto', 'warning');
        return;
    }

    const newProd = {
        id: Date.now(),
        name,
        category: category || 'Consumabili',
        department,
        subcategory: subcategory || '',
        quantity,
        unit,
        price,
        supplier,
        status: quantity > 10 ? 'in-stock' : (quantity > 0 ? 'low-stock' : 'out-of-stock')
    };

    if (!appData.products) appData.products = [];
    appData.products.push(newProd);

    saveToCloud();
    updateAll();

    // Reset Form
    if (document.getElementById('productName')) document.getElementById('productName').value = '';
    if (document.getElementById('productQuantity')) document.getElementById('productQuantity').value = '';
    if (document.getElementById('productPrice')) document.getElementById('productPrice').value = '';

    showNotification(`Prodotto "${name}" aggiunto con successo!`);
}

