function renderSnapshotsList() {
    const container = document.getElementById('snapshotsListContainer');
    if (!container) return;

    let snapshots = appData.monthlySnapshots || [];
    if (currentRole !== 'admin') {
        snapshots = snapshots.filter(s => !s.department || s.department === currentRole || s.department === 'tutti');
    }

    if (snapshots.length === 0) {
        container.innerHTML = '<p style="text-align: center; color: var(--gray); padding: 1.5rem;">Nessuno snapshot salvato</p>';
        return;
    }

    const currency = appData.settings?.currency === 'EUR' ? '€' : '$';

    container.innerHTML = snapshots.slice().reverse().map(s => {
        const dateObj = new Date(s.date);
        const dateFormatted = isNaN(dateObj) ? s.date : dateObj.toLocaleDateString('it-IT', { year: 'numeric', month: 'long', day: 'numeric', hour: '2-digit', minute: '2-digit' });
        const opLabel = s.operator || 'Snapshot';

        return `
            <div style="display: flex; justify-content: space-between; align-items: center; padding: 0.75rem 1rem; border: 1px solid var(--border); border-radius: 8px; margin-bottom: 0.5rem; background: #fdfdfd;">
                <div>
                    <strong>${opLabel} - ${dateFormatted}</strong>
                    <div style="font-size: 0.85rem; color: var(--gray);">${s.products ? s.products.length : (s.productsCount || 0)} Prodotti ${s.totalValue ? `· ${currency} ${Number(s.totalValue).toFixed(2)}` : ''}</div>
                </div>
                <div class="table-actions">
                    <button class="action-btn" onclick="exportSnapshot(${s.id})" title="Esporta"><i class="fas fa-file-excel"></i></button>
                    ${currentRole === 'admin' ? `<button class="action-btn delete" onclick="deleteSnapshot(${s.id})" title="Elimina"><i class="fas fa-trash-alt"></i></button>` : ''}
                </div>
            </div>
        `;
    }).join('');
}

