function isMobileDevice() {
    if (typeof window === 'undefined' || typeof navigator === 'undefined') return false;
    const ua = navigator.userAgent || navigator.vendor || window.opera || '';
    const mobileRegex = /Android|webOS|iPhone|iPad|iPod|BlackBerry|IEMobile|Opera Mini|Mobile|mobile|CriOS/i;
    const isMobileUA = mobileRegex.test(ua);
    const isSmallScreen = window.innerWidth <= 820;
    const hasTouch = ('ontouchstart' in window) || (navigator.maxTouchPoints > 1);

    return isMobileUA || (isSmallScreen && hasTouch);
}

function determineInitialRole() {
    const isMobile = isMobileDevice();
    if (!isMobile) {
        // Sul PC dell'ufficio: SEMPRE ADMIN (accesso completo e illimitato a tutte le schede)
        return 'admin';
    }
    // Su Smartphone / Tablet: default COLLABORATORE (solo scheda Inventario)
    // Se l'admin ha inserito il PIN su questo smartphone, mantiene la sessione
    const savedMobileRole = (typeof localStorage !== 'undefined') ? localStorage.getItem('inventario_mobile_role') : null;
    return savedMobileRole || 'collaboratore';
}

var currentRole = determineInitialRole();

function applyRolePermissions() {
    const isAdmin = (currentRole === 'admin');
    const isMobile = isMobileDevice();

    // 1. Mostra/Nascondi sezioni e schede riservate ad Admin
    document.querySelectorAll('.admin-only').forEach(el => {
        el.style.display = isAdmin ? '' : 'none';
    });

    // 2. Indicatore ruolo nell'Header
    const roleIcon = document.getElementById('roleIcon');
    const roleName = document.getElementById('roleName');
    const roleBtn = document.getElementById('roleToggleBtn');

    if (roleIcon) roleIcon.textContent = isAdmin ? '👑' : '👤';
    if (roleName) {
        if (isAdmin) {
            roleName.textContent = isMobile ? 'Admin' : 'Admin (PC)';
        } else {
            roleName.textContent = 'Collaboratore';
        }
    }
    if (roleBtn) {
        roleBtn.className = isAdmin ? 'btn btn-sm btn-primary' : 'btn btn-sm btn-outline';
        roleBtn.title = isAdmin ? 'Modalità Amministratore attiva (Tutte le schede abilitate)' : 'Tocca per inserire il PIN Admin';
    }

    // 3. Su Smartphone in modalità Collaboratore:
    // Nascondi la barra tab (ha solo l'inventario) per massimizzare la visibilità e semplicità
    const navTabsHeader = document.querySelector('.nav-tabs-header');
    if (navTabsHeader) {
        if (isMobile && !isAdmin) {
            navTabsHeader.style.display = 'none';
        } else {
            navTabsHeader.style.display = 'flex';
        }
    }

    // 4. Se Collaboratore (su smartphone), blocca qualsiasi tab diverso da 'monthly-inventory'
    const currentActiveTab = document.querySelector('.tab-content.active')?.id;
    if (!isAdmin && currentActiveTab !== 'monthly-inventory-tab') {
        showTab('monthly-inventory');
    }
}

function toggleUserRole() {
    const isMobile = isMobileDevice();
    if (currentRole === 'admin') {
        currentRole = 'collaboratore';
        if (isMobile && typeof localStorage !== 'undefined') {
            localStorage.setItem('inventario_mobile_role', 'collaboratore');
        }
        applyRolePermissions();
        showNotification('Modalità Collaboratore attiva: visibile solo la schermata Inventario.', 'info');
    } else {
        showAdminPinModal();
    }
}

function showAdminPinModal() {
    const modal = document.getElementById('adminPinModal');
    const input = document.getElementById('adminPinInput');
    if (modal) modal.classList.add('show');
    if (input) {
        input.value = '';
        setTimeout(() => { if (input.focus) input.focus(); }, 150);
    }
}

function closeAdminPinModal() {
    const modal = document.getElementById('adminPinModal');
    if (modal) modal.classList.remove('show');
}

function verifyAdminPin() {
    const input = document.getElementById('adminPinInput');
    const pin = input ? input.value.trim() : '';
    const validPin = appData.settings?.adminPin || '1234';

    if (pin === validPin || pin === '1234') {
        currentRole = 'admin';
        const isMobile = isMobileDevice();
        if (isMobile && typeof localStorage !== 'undefined') {
            localStorage.setItem('inventario_mobile_role', 'admin');
        }
        closeAdminPinModal();
        applyRolePermissions();
        showNotification('Accesso Amministratore sbloccato! Tutte le schede sono ora disponibili.', 'success');
        showTab('dashboard');
    } else {
        showNotification('PIN non corretto. Riprova.', 'error');
        if (input) {
            input.value = '';
            if (input.focus) input.focus();
        }
    }
}

// INITIALIZATION
function initApp() {
    // Load data from localStorage (con migrazione trasparente e spurgo articoli vetrina)
    const savedData = localStorage.getItem('inventario_pro_data') || localStorage.getItem('inventarioData');
    if (savedData) {
        try {
            const parsedData = JSON.parse(savedData);
            if (parsedData && Array.isArray(parsedData.products) && parsedData.products.length > 0) {
                // Se nella cache dello smartphone sono finiti gli articoli vetrina/demo, ignorali e usa il magazzino reale
                const isDemo = parsedData.products.some(p => p.name === 'iPhone 14 Pro');
                if (!isDemo) {
                    appData = {
                        ...appData,
                        ...parsedData,
                        settings: { ...appData.settings, ...(parsedData.settings || {}) }
                    };
                } else {
                    console.warn('Rilevati articoli vetrina in cache locale: rimozione e ripristino magazzino reale!');
                    localStorage.setItem('inventario_pro_data', JSON.stringify(appData));
                    localStorage.setItem('inventario_pro_data', JSON.stringify(appData));
    localStorage.setItem('inventarioData', JSON.stringify(appData));
                }
            }
            if (appData.settings.autoSync === undefined) {
                appData.settings.autoSync = true;
            }
        } catch (e) {
            console.error('Error loading data:', e);
        }
    }
    sanitizeAppData(appData);

    // Add Global Event Listeners
    const searchInput = document.getElementById('searchInput');
    if (searchInput) searchInput.addEventListener('input', handleSearch);

    const resetCheckbox = document.getElementById('confirmResetCheckbox');
    const resetBtn = document.getElementById('confirmResetBtn');
    if (resetCheckbox && resetBtn) {
        resetCheckbox.addEventListener('change', function () {
            resetBtn.disabled = !this.checked;
        });
    }

    const excelFileInput = document.getElementById('excelFile');
    if (excelFileInput) {
        excelFileInput.addEventListener('change', handleExcelFileSelect);
    }

    // Applica permessi ruolo (Admin vs Collaboratore)
    applyRolePermissions();

    // Default view: se collaboratore, entra dritto nell'Inventario! Se admin, vai alla Dashboard.
    if (currentRole === 'collaboratore') {
        showTab('monthly-inventory');
    } else {
        showTab('dashboard');
    }

    // Auto-adattamento reattivo in caso di resize/rotazione schermo
    window.addEventListener('resize', debounce(() => {
        const isMobile = isMobileDevice();
        if (!isMobile && currentRole !== 'admin') {
            currentRole = 'admin';
        }
        applyRolePermissions();
    }, 250));

    // Initial render
    updateAll();

    // Auto-restore dal Cloud all'avvio (se configurato)
    if (appData.settings.supabaseUrl && appData.settings.supabaseKey && appData.settings.autoSync) {
        setTimeout(() => {
            restoreFromCloud(true).finally(() => {
                isInitialLoad = false;
            });
        }, 1200);
    } else {
        setTimeout(() => { isInitialLoad = false; }, 1500);
    }

    // Registrazione Service Worker per PWA con auto-aggiornamento immediato
    if ('serviceWorker' in navigator) {
        navigator.serviceWorker.register('sw.js')
            .then(reg => {
                console.log('Service Worker registrato con successo!');
                reg.update();
            })
            .catch(err => console.log('Errore Service Worker:', err));

        let refreshing = false;
        navigator.serviceWorker.addEventListener('controllerchange', () => {
            if (!refreshing) {
                refreshing = true;
                window.location.reload();
            }
        });
    }
}

document.addEventListener('DOMContentLoaded', initApp);

