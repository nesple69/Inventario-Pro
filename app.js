    const labels = hasData ? ['🍳 Cucina', '🍹 Bar', '🎳 Bowling', '🏢 Condivisi'] : ['Nessun valore a magazzino'];
    const bgColors = hasData ? ['#fb8500', '#8338ec', '#10b981', '#4361ee'] : ['#e9ecef'];

