        category: category || 'Consumabili',
        department,
        subcategory: subcategory || '',
        quantity,
        unit,
        price,
        supplier,
        status: quantity > 10 ? 'in-stock' : (quantity > 0 ? 'low-stock' : 'out-of-stock')
